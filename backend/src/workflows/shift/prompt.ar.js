const KNOWLEDGE_SECTORS = ['clinic', 'restaurant', 'store', 'other'];

// PR1's SHIFT_KNOWLEDGE stays the single source of product facts; the sector sub-bullets of product 1
// are recognised by their prefix. `other` has no sub-bullet (its recommendations live in the template).
const SECTOR_BULLETS = {
  clinic: /^\s*-\s*للعيادات:/,
  restaurant: /^\s*-\s*للمطاعم/,
  store: /^\s*-\s*للمتاجر/,
};

function bulletSector(line) {
  return Object.keys(SECTOR_BULLETS).find((s) => SECTOR_BULLETS[s].test(line)) || null;
}

const KNOWLEDGE_LINES = SHIFT_KNOWLEDGE.split('\n');

const KNOWLEDGE_SECTIONS = {
  common: KNOWLEDGE_LINES.filter((l) => bulletSector(l) === null).join('\n'),
  clinic: KNOWLEDGE_LINES.filter((l) => bulletSector(l) === 'clinic').join('\n'),
  restaurant: KNOWLEDGE_LINES.filter((l) => bulletSector(l) === 'restaurant').join('\n'),
  store: KNOWLEDGE_LINES.filter((l) => bulletSector(l) === 'store').join('\n'),
  other: '',
};

/**
 * Knowledge for one sector: the common lines, that sector's bullet kept in its original place under
 * product 1, and the operational FAQ. An unknown sector gets every sector's bullet.
 */
function knowledgeFor(sector) {
  const known = KNOWLEDGE_SECTORS.includes(sector);
  const lines = KNOWLEDGE_LINES.filter((l) => {
    const s = bulletSector(l);
    return s === null || !known || s === sector;
  });
  return `${lines.join('\n')}\n${OPERATIONAL_FAQ}`;
}

const cache = new Map();

/** The static prompt for a sector; identical strings per sector so the provider can cache it. */
function buildStaticPrompt({ sector } = {}) {
  const key = KNOWLEDGE_SECTORS.includes(sector) ? sector : '*';
  if (!cache.has(key)) {
    cache.set(key, SHIFT_SYSTEM_PROMPT_TEMPLATE.replace('{{SHIFT_KNOWLEDGE}}', () => knowledgeFor(key === '*' ? null : key)));
  }
  return cache.get(key);
}

